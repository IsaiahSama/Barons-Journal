"""Regenerate src/barons_journal/reference/alchemy.json from a Barony source checkout.

Usage:
    uv run python scripts/build_alchemy_table.py /path/to/Barony [--commit SHA]

Sources (src/interface/interface.cpp):
- Base / secondary ingredients: GenericGUIMenu::isItemBaseIngredient and
  ::isItemSecondaryIngredient, in the order they're listed.
- Recipes: the first `switch ( potion1 )` in alchemyMixResult. Its second half
  repeats the same table with the arguments swapped, so it's skipped. Cases that
  don't set a fixed result (water, polymorph, acid explosions) are rules, which
  live in code in reference/alchemy.py, not in the table.
Item IDs come from the ItemType enum in src/items.hpp.
"""

import argparse
import json
import re
from pathlib import Path

OUT = Path(__file__).parent.parent / "src/barons_journal/reference/alchemy.json"


def item_ids(barony: Path) -> dict[str, int]:
    src = (barony / "src/items.hpp").read_text(encoding="utf-8")
    body = src[src.index("typedef enum ItemType") :]
    body = re.sub(r"//.*", "", body[body.index("{") + 1 : body.index("} ItemType")])
    names = [m.split("=")[0].strip() for m in body.split(",") if m.strip()]
    return {name: i for i, name in enumerate(names)}


def function_body(src: str, signature: str) -> str:
    """Text of a C++ function body, by brace matching from its signature."""
    start = src.index("{", src.index(signature))
    depth = 0
    for i in range(start, len(src)):
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        if depth == 0:
            return src[start : i + 1]
    raise ValueError(f"unbalanced braces after {signature!r}")


def ingredient_list(src: str, signature: str) -> list[str]:
    body = function_body(src, signature)
    return re.findall(r"case (POTION_\w+):", body)


def recipes(src: str) -> list[tuple[str, str, str]]:
    body = function_body(src, "ItemType alchemyMixResult(")
    first_switch = body[body.index("switch ( potion1 )") : body.index("if ( result == POTION_SICKNESS )")]
    found = []
    # Each top-level case: `case POTION_X:` followed by an inner `switch ( potion2 )`.
    for block in re.split(r"\n\t\tcase ", first_switch)[1:]:
        base = block.split(":", 1)[0].strip()
        for secondary, result in re.findall(r"case (POTION_\w+):\s*result = (POTION_\w+);", block):
            found.append((base, secondary, result))
    return found


def build(barony: Path) -> dict:
    ids = item_ids(barony)
    src = (barony / "src/interface/interface.cpp").read_text(encoding="utf-8")

    base = ingredient_list(src, "bool GenericGUIMenu::isItemBaseIngredient(")
    secondary = ingredient_list(src, "bool GenericGUIMenu::isItemSecondaryIngredient(")
    table = recipes(src)

    assert len(table) == 24, f"expected 24 fixed recipes, found {len(table)}"
    for b, s, _ in table:
        assert b in base and s in secondary, (b, s)

    # Keep table order: base ingredient order, then secondary order.
    table.sort(key=lambda r: (base.index(r[0]), secondary.index(r[1])))
    return {
        "base_ingredients": [ids[name] for name in base],
        "secondary_ingredients": [ids[name] for name in secondary],
        "recipes": [{"base": ids[b], "secondary": ids[s], "result": ids[r]} for b, s, r in table],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("barony", type=Path, help="path to a TurningWheel/Barony checkout")
    parser.add_argument("--commit", default="unknown", help="Barony commit SHA, recorded for provenance")
    args = parser.parse_args()

    tables = build(args.barony)
    out = {"_source": f"TurningWheel/Barony@{args.commit}, generated by scripts/build_alchemy_table.py", **tables}
    OUT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"recipes {len(tables['recipes'])}\nwrote {OUT}")


if __name__ == "__main__":
    main()
