"""Regenerate src/barons_journal/reference/scrolls.json.

Usage:
    uv run python scripts/build_scroll_tables.py /path/to/Barony \\
        --game-dir ~/.steam/steam/steamapps/common/Barony [--commit SHA] [--game-build ID]

Sources:
- Labels: `scroll_label` in src/scrolls.hpp (source checkout), in game order.
- Label counts: how often each scroll appears in `enchantedFeatherScrollsFixedList`
  in src/items.hpp. Each run shuffles that list and gives label i to entry i, so
  a scroll that appears 3 times there gets 3 different labels in every run.
- Value, weight: items/items.json (installed game).
- Effect text: items/item_tooltips.json (installed game).
- Names: lang/item_names.json (source checkout), same as ids.json.
"""

import argparse
import json
import re
from collections import Counter
from pathlib import Path

OUT = Path(__file__).parent.parent / "src/barons_journal/reference/scrolls.json"


def read_labels(barony: Path) -> list[str]:
    src = (barony / "src/scrolls.hpp").read_text(encoding="utf-8")
    num = int(re.search(r"#define NUMLABELS (\d+)", src).group(1))
    body = src[src.index("scroll_label[NUMLABELS]") :]
    body = body[body.index("{") + 1 : body.index("};")]
    labels = re.findall(r'"([^"]*)"', body)
    assert len(labels) == num, (len(labels), num)
    return labels


def read_label_counts(barony: Path) -> Counter[str]:
    src = (barony / "src/items.hpp").read_text(encoding="utf-8")
    body = src[src.index("enchantedFeatherScrollsFixedList") :]
    body = body[body.index("{") + 1 : body.index("};")]
    return Counter(re.findall(r"SCROLL_\w+", body))


def clean_tooltip(text: str) -> str:
    """'[Summons] flames\\nat current location' -> 'Summons flames at current location'."""
    return re.sub(r"\s+", " ", text.replace("[", "").replace("]", "")).strip()


def read_effects(game_dir: Path) -> dict[str, str]:
    """Item key (e.g. 'scroll_fire') -> one-line effect text."""
    tooltips = json.loads((game_dir / "items/item_tooltips.json").read_text(encoding="utf-8"))["tooltips"]
    effects = {
        icon["conditional_attribute"]: clean_tooltip(icon["text"])
        for icon in tooltips["tooltip_scroll"]["icons"]
        if icon.get("conditional_attribute", "").startswith("scroll_")
    }
    # Mail and blank scrolls have their own tooltips without a per-scroll effect line.
    effects["scroll_mail"] = " ".join(tooltips["tooltip_scroll_mail"]["description"])
    blank = tooltips["tooltip_scroll_blank"]
    effects["scroll_blank"] = f"{clean_tooltip(blank['icons'][0]['text'])}. {' '.join(blank['description'])}"
    return effects


def build(barony: Path, game_dir: Path) -> dict:
    labels = read_labels(barony)
    label_counts = read_label_counts(barony)
    assert sum(label_counts.values()) == len(labels), "fixed list length != NUMLABELS"

    effects = read_effects(game_dir)
    names = json.loads((barony / "lang/item_names.json").read_text(encoding="utf-8"))["items"]
    game_items = json.loads((game_dir / "items/items.json").read_text(encoding="utf-8"))["items"]

    scrolls = []
    for key, item in game_items.items():
        if item["item_category"] != "SCROLL":
            continue
        enum_name = key.upper()
        scrolls.append(
            {
                "item_id": item["item_id"],
                "name": names[key]["name_identified"],
                "effect": effects[key],
                "value": item["gold_value"],
                "weight": item["weight_value"],
                "label_count": label_counts[enum_name],
            }
        )
    scrolls.sort(key=lambda s: s["item_id"])

    missing = set(label_counts) - {s.upper() for s in game_items if game_items[s]["item_category"] == "SCROLL"}
    assert not missing, f"scrolls in the label list but not in items.json: {missing}"
    assert all(s["label_count"] for s in scrolls), "a scroll type has no label"

    return {"labels": labels, "scrolls": scrolls}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("barony", type=Path, help="path to a TurningWheel/Barony checkout")
    parser.add_argument("--game-dir", type=Path, required=True, help="installed Barony folder (has items/)")
    parser.add_argument("--commit", default="unknown", help="Barony commit SHA, recorded for provenance")
    parser.add_argument("--game-build", default="unknown", help="Steam build ID of --game-dir, for provenance")
    args = parser.parse_args()

    tables = build(args.barony, args.game_dir)
    out = {
        "_source": (
            f"TurningWheel/Barony@{args.commit} + game data from Steam build {args.game_build}, "
            "generated by scripts/build_scroll_tables.py"
        ),
        **tables,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"labels  {len(tables['labels'])}\nscrolls {len(tables['scrolls'])}\nwrote {OUT}")


if __name__ == "__main__":
    main()
