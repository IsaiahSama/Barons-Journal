"""Alchemy: which potions can be combined at an alembic, and what they make.

Data lives in alchemy.json, generated by scripts/build_alchemy_table.py from
`alchemyMixResult` in Barony's src/interface/interface.cpp. All IDs are item
type IDs (see ``data.ids.ITEMS``).

The alembic has a base slot and a secondary slot. Most useful pairs have a fixed
result (``RECIPES``); the rest follow a few rules, which ``mix`` applies.
"""

import json
from dataclasses import dataclass
from importlib.resources import files
from typing import Literal

from ..data.ids import ITEMS

_data = json.loads(files(__package__).joinpath("alchemy.json").read_text(encoding="utf-8"))

BASE_INGREDIENTS: tuple[int, ...] = tuple(_data["base_ingredients"])
"""Item IDs allowed in the base slot."""
SECONDARY_INGREDIENTS: tuple[int, ...] = tuple(_data["secondary_ingredients"])
"""Item IDs allowed in the secondary slot."""

_WATER = 53  # POTION_WATER
_ACID = 66  # POTION_ACID
_POLYMORPH = 218  # POTION_POLYMORPH


@dataclass(frozen=True, slots=True)
class Recipe:
    base: int
    secondary: int
    result: int

    @property
    def base_name(self) -> str:
        return ITEMS.label(self.base)

    @property
    def secondary_name(self) -> str:
        return ITEMS.label(self.secondary)

    @property
    def result_name(self) -> str:
        return ITEMS.label(self.result)


RECIPES: tuple[Recipe, ...] = tuple(Recipe(**r) for r in _data["recipes"])
"""Every fixed-result pair, ordered by base ingredient, then secondary ingredient."""

_BY_PAIR = {(r.base, r.secondary): r for r in RECIPES}

del _data


@dataclass(frozen=True, slots=True)
class Mix:
    """The outcome of combining two potions.

    kind:
        "potion"    you get ``potion`` (a fixed recipe)
        "duplicate" water copies the other ingredient: you get two of ``potion``
        "random"    polymorph makes the result a random potion
        "explodes"  acid and water explode
        "same"      both slots hold ``potion``
    """

    kind: Literal["potion", "duplicate", "random", "explodes", "same"]
    potion: int | None = None


def mix(base: int, secondary: int) -> Mix:
    """What combining these two potions does, following the game's rules.

    Raises ``ValueError`` if either potion can't go in its slot.
    """
    if base not in BASE_INGREDIENTS:
        raise ValueError(f"{ITEMS.label(base)} is not a base ingredient")
    if secondary not in SECONDARY_INGREDIENTS:
        raise ValueError(f"{ITEMS.label(secondary)} is not a secondary ingredient")

    # Same order of checks as alchemyMixResult.
    if base == secondary:
        return Mix("same", base)
    if {base, secondary} == {_ACID, _WATER}:
        return Mix("explodes")
    if _POLYMORPH in (base, secondary):
        return Mix("random")
    if _WATER in (base, secondary):
        return Mix("duplicate", secondary if base == _WATER else base)
    return Mix("potion", _BY_PAIR[(base, secondary)].result)


def recipes_making(result: int) -> tuple[Recipe, ...]:
    """Every fixed recipe that produces ``result``, in table order."""
    return tuple(r for r in RECIPES if r.result == result)
