"""Scroll types and the labels unidentified scrolls can carry.

Data lives in scrolls.json, generated by scripts/build_scroll_tables.py.

How labels work in Barony: each run shuffles a fixed list of 25 scroll entries
and gives ``SCROLL_LABELS[i]`` to entry ``i``. Some scrolls appear in that list
more than once (see ``Scroll.label_count``), so a single scroll type can show up
under several different labels in the same run. Identifying one label therefore
doesn't rule that scroll type out for the other labels.
"""

import json
from dataclasses import dataclass
from importlib.resources import files


@dataclass(frozen=True, slots=True)
class Scroll:
    item_id: int
    """Item type ID, as in the save's inventory and ``data.ids.ITEMS``."""
    name: str
    effect: str
    value: int
    """Base gold value."""
    weight: int
    label_count: int
    """How many of the 25 labels this scroll type takes in every run."""


_data = json.loads(files(__package__).joinpath("scrolls.json").read_text(encoding="utf-8"))

SCROLL_LABELS: tuple[str, ...] = tuple(_data["labels"])
"""Every label an unidentified scroll can have, in the game's order."""

SCROLLS: tuple[Scroll, ...] = tuple(Scroll(**s) for s in _data["scrolls"])
"""Every scroll type, in item-ID order."""

_BY_ITEM_ID = {s.item_id: s for s in SCROLLS}

del _data


def scroll_by_item_id(item_id: int) -> Scroll:
    """Look up a scroll by item type. Raises ``KeyError`` if the item isn't a scroll."""
    return _BY_ITEM_ID[item_id]
