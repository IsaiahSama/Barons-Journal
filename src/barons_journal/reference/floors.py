"""The floor map: every main floor, which ones have a secret entrance, and what each secret level holds.

Data lives in floors.json, generated by scripts/build_floor_table.py from the
game's level lists, the compendium, and Barony's maps.cpp.

Floors are numbered by ``dungeon_lvl``, the same number as ``SaveFile.dungeon_lvl``
(0 is the Minehead). A secret entrance on main floor N leads to the secret level
at depth N+1. Secret levels are identified by their depth, because the Underworld
appears at four depths.
"""

import json
from dataclasses import dataclass
from importlib.resources import files

from ..data.ids import ITEMS


@dataclass(frozen=True, slots=True)
class SecretLevel:
    dungeon_lvl: int
    """Depth of this secret level (unique; use it as the key)."""
    name: str
    """Display name from the compendium, e.g. "Haunted Castle"."""
    entrance_floor: int | None
    """Main floor whose secret entrance leads here, or None if reached from ``previous``."""
    previous: str | None
    """Secret level this one is reached from (the Underworld's second floor, by trapdoor)."""
    treasures: tuple[str, ...]
    """The compendium's "SECRET LEVEL TREASURES" lines, as written."""
    artifacts: tuple[int, ...]
    """Item IDs of the artifacts among ``treasures``."""

    @property
    def artifact_names(self) -> tuple[str, ...]:
        return tuple(ITEMS.label(i) for i in self.artifacts)


@dataclass(frozen=True, slots=True)
class Floor:
    dungeon_lvl: int
    area: str
    """Display name from the compendium, e.g. "Mines", "Transition Floor"."""
    secret_entrance: SecretLevel | None
    """Where this floor's secret entrance leads, if it has one."""
    secret_entrance_chance: float | None
    """1.0 if the entrance is always there, 0.5 if only some runs have it; None without one."""
    orb: int | None
    """Item ID of the mystic orb this floor always has a room for, if any."""

    @property
    def orb_name(self) -> str | None:
        return ITEMS.label(self.orb) if self.orb is not None else None


_data = json.loads(files(__package__).joinpath("floors.json").read_text(encoding="utf-8"))

SECRET_LEVELS: tuple[SecretLevel, ...] = tuple(
    SecretLevel(
        dungeon_lvl=s["dungeon_lvl"],
        name=s["name"],
        entrance_floor=s["entrance_floor"],
        previous=s["previous"],
        treasures=tuple(s["treasures"]),
        artifacts=tuple(s["artifacts"]),
    )
    for s in _data["secret_levels"]
)
"""Every secret level, by depth."""

_SECRET_BY_LVL = {s.dungeon_lvl: s for s in SECRET_LEVELS}

FLOORS: tuple[Floor, ...] = tuple(
    Floor(
        dungeon_lvl=f["dungeon_lvl"],
        area=f["area"],
        secret_entrance=_SECRET_BY_LVL[f["secret_entrance"]] if f["secret_entrance"] is not None else None,
        secret_entrance_chance=f["secret_entrance_chance"],
        orb=f["orb"],
    )
    for f in _data["floors"]
)
"""Every main floor, indexed by dungeon_lvl."""

del _data


def floor_at(dungeon_lvl: int) -> Floor:
    """The main floor at this depth. Raises ``KeyError`` past the last floor."""
    if not 0 <= dungeon_lvl < len(FLOORS):
        raise KeyError(f"no floor {dungeon_lvl}")
    return FLOORS[dungeon_lvl]


def secret_level_at(dungeon_lvl: int) -> SecretLevel | None:
    """The secret level at this depth, if there is one."""
    return _SECRET_BY_LVL.get(dungeon_lvl)


def artifact_locations() -> dict[int, tuple[SecretLevel, ...]]:
    """Artifact item ID -> the secret levels it can be found in, by depth."""
    found: dict[int, list[SecretLevel]] = {}
    for secret in SECRET_LEVELS:
        for item_id in secret.artifacts:
            found.setdefault(item_id, []).append(secret)
    return {item_id: tuple(levels) for item_id, levels in found.items()}


def orb_floors() -> dict[int, Floor]:
    """Mystic orb item ID -> the main floor it's found on."""
    return {f.orb: f for f in FLOORS if f.orb is not None}
